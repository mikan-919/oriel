// Build Web assets and review fixtures first. Requires Relay's Playwright dependency.
import assert from "node:assert/strict";
import {chromium} from "../../oriel-relay/node_modules/playwright/index.mjs";

const browser = await chromium.launch({headless:true});
try {
  const page = await browser.newPage({viewport:{width:Number(process.env.REVIEW_WIDTH || 1440),height:Number(process.env.REVIEW_HEIGHT || 800)}}); const errors = [];
  await page.clock.install();
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(new URL("../build/review/codex.html", import.meta.url).href);
  await page.getByText("今回だけ許可", {exact:true}).waitFor();
  const latest = method => page.evaluate(method => window.fixtureRPCs.filter(r => r.method === method).at(-1), method);
  await page.getByText("今回だけ許可", {exact:true}).click();
  await page.waitForFunction(() => window.fixtureRPCs.some(r => r.method === "request/respond"));
  assert.equal((await latest("request/respond")).engine, "automatic");
  assert.equal((await latest("request/respond")).params.decision, "accept");
  await page.getByRole("button", {name:"全体", exact:true}).click();
  await page.getByRole("button", {name:"回答を送信", exact:true}).click();
  await page.waitForFunction(() => window.fixtureRPCs.filter(r => r.method === "request/respond").length === 2);
  assert.deepEqual((await latest("request/respond")).params.answers, {choice:{answers:["全体"]}});
  await page.locator("#codex-new").click();
  await page.waitForFunction(() => !document.getElementById("codex-send").disabled);
  await page.locator("#codex-model").selectOption("test-model");
  await page.locator("#codex-effort").selectOption("high");
  await page.locator("#codex-input").fill("変更内容を説明してください。");
  await page.locator("#codex-send").click();
  await page.waitForFunction(() => !document.getElementById("codex-steer").disabled);
  assert.equal((await latest("turn/start")).params.effort, "high");
  await page.locator("#codex-input").fill("インストール手順も確認してください。");
  await page.locator("#codex-steer").click();
  await page.waitForFunction(() => window.fixtureRPCs.some(r => r.method === "turn/steer"));
  assert.equal((await latest("turn/steer")).params.expectedTurnId, "running");
  await page.locator("#codex-interrupt").click();
  await page.waitForFunction(() => !document.getElementById("codex-fork").disabled);
  await page.locator("#codex-fork").click();
  await page.waitForFunction(() => window.fixtureRPCs.some(r => r.method === "thread/fork"));
  await page.locator("#codex-name").fill("確認用の会話");
  await page.locator("#codex-rename").click();
  await page.waitForFunction(() => window.fixtureRPCs.some(r => r.method === "thread/name/set"));
  assert.equal((await latest("thread/name/set")).params.name, "確認用の会話");
  await page.locator("#codex-review").click();
  await page.waitForFunction(() => !document.getElementById("codex-interrupt").disabled);
  assert.equal((await latest("review/start")).params.target.type, "uncommittedChanges");
  await page.locator("#codex-interrupt").click();
  await page.waitForFunction(() => !document.getElementById("codex-archive").disabled);
  await page.locator("#codex-archive").click();
  await page.waitForFunction(() => window.fixtureRPCs.some(r => r.method === "thread/archive"));
  await page.locator("#codex-archived").check();
  await page.getByRole("button", {name:"保存した会話", exact:true}).click();
  await page.waitForFunction(() => !document.getElementById("codex-archive").disabled);
  await page.locator("#codex-archive").click();
  await page.waitForFunction(() => window.fixtureRPCs.some(r => r.method === "thread/unarchive"));
  await page.locator("#codex-pause").click();
  await page.waitForFunction(() => document.getElementById("codex-status").textContent.includes("一時停止"));
  await page.locator("#codex-resume").click();
  await page.waitForFunction(() => window.fixtureRPCs.some(r => r.method === "workflow/resume"));
  await page.getByText("スキルと外部サービス", {exact:true}).click();
  await page.locator("#codex-skills").click();
  await page.getByRole("button", {name:"example-skill", exact:true}).click();
  assert.ok((await page.locator("#codex-input").inputValue()).startsWith("$example-skill"));
  await page.getByRole("button", {name:"認可する", exact:true}).click();
  assert.equal(await page.getByRole("link", {name:"認可画面を開く"}).getAttribute("href"), "https://example.com/authorize");
  await page.locator("#codex-mcp-name").fill("docs");
  await page.locator("#codex-mcp-url").fill("https://example.com/mcp");
  await page.getByRole("button", {name:"接続先を保存", exact:true}).click();
  await page.waitForFunction(() => window.fixtureRPCs.some(r => r.method === "mcp/configure"));
  await page.locator("#codex-engine").selectOption("automatic");
  assert.equal(await page.locator("#codex-new").isDisabled(), true);
  assert.equal(await page.locator("#codex-send").isDisabled(), true);
  await page.waitForFunction(() => !document.getElementById("codex-interrupt").disabled);
  await page.waitForTimeout(50);
  const callsBeforeIdle = await page.evaluate(() => {
    window.beforeIdleConnection = window.fixtureCodex;
    return window.fixtureRPCs.length;
  });
  await page.clock.runFor(90000);
  assert.equal(await page.evaluate(() => window.fixtureCodex === window.beforeIdleConnection && window.fixtureCodex.readyState === 1), true);
  assert.equal(await page.evaluate(() => window.fixtureRPCs.length), callsBeforeIdle, "Idle keepalive must not issue Codex RPCs");
  await page.evaluate(() => {
    const send = window.fixtureCodex.send.bind(window.fixtureCodex);
    window.fixtureCodex.send = raw => {if (raw !== "oriel:ping") send(raw);};
  });
  await page.clock.runFor(61000);
  assert.equal(await page.locator("#codex-interrupt").isDisabled(), true, "Missing pongs must disconnect the control channel");
  assert.deepEqual(errors, []);
  console.log("Codex browser: approvals, questions, conversations, models, steering, interrupt, fork, pause/resume, skills, MCP and authority passed");
} finally { await browser.close(); }
